/**
 * Defines the core action graph model for Bazel's execution phase.
 *
 * <p>This package contains the interfaces and classes that represent build actions (functions from
 * input artifacts to output artifacts), the artifacts themselves (source and derived files in the
 * build), and the infrastructure for spawning subprocesses, managing resources, and executing
 * actions. It forms the contract between the analysis phase (which produces the action graph) and
 * the execution phase (which runs it).
 *
 * <h2>Key Abstractions</h2>
 *
 * <ul>
 *   <li>{@link com.google.devtools.build.lib.actions.Action} &mdash; the central interface
 *       representing an executable build step. An action is a function from {@link
 *       com.google.devtools.build.lib.actions.Artifact Artifact} inputs to {@link
 *       com.google.devtools.build.lib.actions.Artifact Artifact} outputs.
 *   <li>{@link com.google.devtools.build.lib.actions.Artifact} &mdash; represents a file in the
 *       build, either a source file (from the workspace) or a derived file (generated by an
 *       action). This is a sealed class with {@code SourceArtifact} and {@code DerivedArtifact}
 *       subtypes.
 *   <li>{@link com.google.devtools.build.lib.actions.ActionExecutionContext} &mdash; bundles the
 *       services available during action execution, including the exec root, file system, output
 *       streams, metadata providers, and the action context registry.
 *   <li>{@link com.google.devtools.build.lib.actions.Spawn} &mdash; represents a subprocess to be
 *       invoked: its command, arguments, environment, input/output files, execution requirements,
 *       and resource needs. The unit of work dispatched to execution strategies.
 *   <li>{@link com.google.devtools.build.lib.actions.ArtifactRoot} &mdash; the root directory for
 *       an artifact, either a source root (package path entry) or a derived root (output directory
 *       such as {@code bazel-out/k8-fastbuild/bin/}).
 *   <li>{@link com.google.devtools.build.lib.actions.ActionLookupValue} &mdash; a Skyframe {@link
 *       com.google.devtools.build.skyframe.SkyValue SkyValue} that provides the generating actions
 *       for artifacts, bridging analysis-phase configured targets and the action graph.
 * </ul>
 *
 * <h2>Architectural Role</h2>
 *
 * <p>The analysis phase (in {@link com.google.devtools.build.lib.analysis}) produces a graph of
 * {@link com.google.devtools.build.lib.actions.Action Action} objects with {@link
 * com.google.devtools.build.lib.actions.Artifact Artifact} inputs and outputs. The execution phase
 * (driven by Skyframe via {@code ActionExecutionFunction}) then executes these actions, using {@link
 * com.google.devtools.build.lib.actions.Spawn Spawn} objects dispatched to strategy
 * implementations (local, remote, sandboxed, dynamic).
 */
package com.google.devtools.build.lib.actions;
